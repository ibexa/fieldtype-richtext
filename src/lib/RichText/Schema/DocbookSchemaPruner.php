declare(strict_types=1);

namespace Ibexa\FieldTypeRichText\RichText\Schema;

use DOMDocument;
use DOMElement;
use DOMNode;
use DOMText;
use DOMXPath;
use Ibexa\FieldTypeRichText\RichText\Exception\DocbookSchemaPruningException;

/**
 * Generates pruned/docbook.rng and pruned/ezpublish.rng from docbook.rng and ezpublish.rng.
 *
 * libxml compiles the whole grammar on every validation, and most of the DocBook definitions
 * are never reachable from ezpublish.rng. pruned/docbook.rng keeps only the reachable
 * definitions, without annotations.
 *
 * libxml also applies every override in <include> by scanning the whole included grammar,
 * which costs more than compiling the pruned grammar itself. pruned/docbook.rng therefore
 * contains the start pattern and the definitions from ezpublish.rng's <include> in place of
 * the ones they replace, and pruned/ezpublish.rng is ezpublish.rng including it without
 * overrides.
 *
 * The files keep the original names: RichTextDocbookSchemaPass (5.0+) finds the base schema
 * in the validator resources by the "ezpublish.rng" file name.
 *
 * @internal
 */
final class DocbookSchemaPruner
{
    public const DOCBOOK_FILE = 'docbook.rng';
    public const EZPUBLISH_FILE = 'ezpublish.rng';

    private const RNG_NAMESPACE = 'https://relaxng.org/ns/structure/1.0';
    private const ALL_DEFINES_XPATH = '//rng:define';
    private const GENERATED_NOTICE = ' Pruned variant of DocBook generated by prune-rng.php from docbook.rng and ezpublish.rng, do not edit. ';

    /**
     * @return array<self::*_FILE, DOMDocument> pruned schemas keyed by the file name they must be saved as
     *
     * @throws DocbookSchemaPruningException if a schema cannot be loaded or does not have the expected structure
     */
    public function prune(
        string $docbookPath,
        string $ezpublishPath
    ): array {
        $docbookXPath = $this->loadSchema($docbookPath);
        $ezpublishXPath = $this->loadSchema($ezpublishPath);
        $docbook = $docbookXPath->document;
        $ezpublish = $ezpublishXPath->document;

        $docbookGrammar = $docbook->documentElement;
        $includes = $this->queryElements($ezpublishXPath, '/rng:grammar/rng:include');
        if ($docbookGrammar === null || count($includes) !== 1) {
            throw new DocbookSchemaPruningException('Expected a docbook.rng grammar and a single <include> in ezpublish.rng');
        }
        $include = $includes[0];

        // The DocBook license requires its copyright notice in all copies.
        $licenseComments = $this->queryNodes($docbookXPath, '/rng:grammar/comment()[following-sibling::rng:start]');

        $overridden = $this->collectOverriddenNames($ezpublishXPath, $include);
        $overridesStart = !empty($this->queryElements($ezpublishXPath, './/rng:start', $include));
        $reachable = $this->collectReachableNames($docbookXPath, $ezpublishXPath, $overridden, $overridesStart);

        $this->removeDefinitions($docbookXPath, $overridden, $reachable, $overridesStart);
        $this->moveIncludeContent($include, $docbookGrammar);
        $this->removeAnnotations($docbookXPath, $licenseComments);
        $this->removeEmptyDivs($docbookXPath);

        $pruned = [
            self::DOCBOOK_FILE => $docbook,
            self::EZPUBLISH_FILE => $ezpublish,
        ];
        foreach ($pruned as $document) {
            $this->addGeneratedNotice($document);
        }

        return $pruned;
    }

    /**
     * Definitions inside <include> replace all included ones with the same name, combine or not.
     *
     * @return array<string, true>
     */
    private function collectOverriddenNames(
        DOMXPath $ezpublishXPath,
        DOMElement $include
    ): array {
        $overridden = [];
        foreach ($this->queryElements($ezpublishXPath, './/rng:define', $include) as $define) {
            $overridden[$define->getAttribute('name')] = true;
        }

        return $overridden;
    }

    /**
     * @param array<string, true> $overridden
     *
     * @return array<string, true>
     *
     * @throws DocbookSchemaPruningException if a reachable reference has no definition
     */
    private function collectReachableNames(
        DOMXPath $docbookXPath,
        DOMXPath $ezpublishXPath,
        array $overridden,
        bool $overridesStart
    ): array {
        $definitions = $this->collectDefinitions($docbookXPath, $ezpublishXPath, $overridden);

        // libxml resolves the references of every definition, used or not.
        $roots = $this->queryElements($ezpublishXPath, '//rng:ref');
        if (!$overridesStart) {
            $roots = array_merge($roots, $this->queryElements($docbookXPath, '//rng:start//rng:ref'));
        }

        $reachable = [];
        $queue = $this->getReferencedNames($roots);
        while (!empty($queue)) {
            $name = array_pop($queue);
            if (isset($reachable[$name])) {
                continue;
            }
            $reachable[$name] = true;
            foreach ($definitions[$name] ?? [] as [$xpath, $define]) {
                $refs = $this->queryElements($xpath, './/rng:ref', $define);
                array_push($queue, ...$this->getReferencedNames($refs));
            }
        }

        $undefined = array_keys(array_diff_key($reachable, $definitions));
        if (!empty($undefined)) {
            throw new DocbookSchemaPruningException('References without a definition: ' . implode(', ', $undefined));
        }

        return $reachable;
    }

    /**
     * @param array<string, true> $overridden
     *
     * @return array<string, array<array{DOMXPath, DOMElement}>> effective definitions by name
     */
    private function collectDefinitions(
        DOMXPath $docbookXPath,
        DOMXPath $ezpublishXPath,
        array $overridden
    ): array {
        $definitions = [];
        foreach ($this->queryElements($docbookXPath, self::ALL_DEFINES_XPATH) as $define) {
            $name = $define->getAttribute('name');
            if (!isset($overridden[$name])) {
                $definitions[$name][] = [$docbookXPath, $define];
            }
        }
        foreach ($this->queryElements($ezpublishXPath, self::ALL_DEFINES_XPATH) as $define) {
            $definitions[$define->getAttribute('name')][] = [$ezpublishXPath, $define];
        }

        return $definitions;
    }

    /**
     * @param DOMElement[] $refs
     *
     * @return string[]
     */
    private function getReferencedNames(array $refs): array
    {
        return array_map(
            static fn (DOMElement $ref): string => $ref->getAttribute('name'),
            $refs
        );
    }

    /**
     * Removes DocBook definitions that are overridden or unreachable, and the start pattern if overridden.
     *
     * @param array<string, true> $overridden
     * @param array<string, true> $reachable
     */
    private function removeDefinitions(
        DOMXPath $docbookXPath,
        array $overridden,
        array $reachable,
        bool $overridesStart
    ): void {
        foreach ($this->queryElements($docbookXPath, self::ALL_DEFINES_XPATH) as $define) {
            $name = $define->getAttribute('name');
            if (isset($overridden[$name]) || !isset($reachable[$name])) {
                $this->removeNode($define);
            }
        }

        if (!$overridesStart) {
            return;
        }
        foreach ($this->queryElements($docbookXPath, '//rng:start') as $start) {
            $this->removeNode($start);
        }
    }

    /**
     * Appended after the included definitions, the order in which libxml combines them.
     * The order matters: moving them before the DocBook definitions changes validation results.
     */
    private function moveIncludeContent(
        DOMElement $include,
        DOMElement $docbookGrammar
    ): void {
        $docbook = $docbookGrammar->ownerDocument;
        if ($docbook === null) {
            throw new DocbookSchemaPruningException('docbook.rng grammar is not attached to a document');
        }

        while ($include->firstChild !== null) {
            $docbookGrammar->appendChild($docbook->importNode($include->firstChild, true));
            $include->removeChild($include->firstChild);
        }
    }

    /**
     * Annotations are ignored by RELAX NG validation.
     *
     * @param DOMNode[] $licenseComments comments to keep
     */
    private function removeAnnotations(
        DOMXPath $docbookXPath,
        array $licenseComments
    ): void {
        $annotations = $this->queryNodes(
            $docbookXPath,
            '//comment() | //*[namespace-uri() != "' . self::RNG_NAMESPACE . '"]'
        );
        foreach ($annotations as $node) {
            if (!in_array($node, $licenseComments, true)) {
                $this->removeNode($node);
            }
        }
    }

    private function removeEmptyDivs(DOMXPath $docbookXPath): void
    {
        while (!empty($emptyDivs = $this->queryElements($docbookXPath, '//rng:div[not(*)]'))) {
            foreach ($emptyDivs as $div) {
                $this->removeNode($div);
            }
        }
    }

    private function addGeneratedNotice(DOMDocument $document): void
    {
        if ($document->documentElement !== null) {
            $document->insertBefore($document->createComment(self::GENERATED_NOTICE), $document->documentElement);
        }
    }

    private function loadSchema(string $path): DOMXPath
    {
        $document = new DOMDocument();
        if (!@$document->load($path)) {
            throw new DocbookSchemaPruningException("Cannot load '{$path}'");
        }

        $xpath = new DOMXPath($document);
        $xpath->registerNamespace('rng', self::RNG_NAMESPACE);

        return $xpath;
    }

    /**
     * @return DOMNode[]
     */
    private function queryNodes(
        DOMXPath $xpath,
        string $expression,
        ?DOMNode $contextNode = null
    ): array {
        $nodes = $xpath->query($expression, $contextNode);
        if ($nodes === false) {
            throw new DocbookSchemaPruningException("Invalid XPath expression '{$expression}'");
        }

        $result = [];
        foreach ($nodes as $node) {
            if ($node instanceof DOMNode) {
                $result[] = $node;
            }
        }

        return $result;
    }

    /**
     * @return DOMElement[]
     */
    private function queryElements(
        DOMXPath $xpath,
        string $expression,
        ?DOMNode $contextNode = null
    ): array {
        return array_values(array_filter(
            $this->queryNodes($xpath, $expression, $contextNode),
            static fn (DOMNode $node): bool => $node instanceof DOMElement
        ));
    }

    private function removeNode(DOMNode $node): void
    {
        $parent = $node->parentNode;
        if ($parent === null) {
            return;
        }

        $previous = $node->previousSibling;
        if ($previous instanceof DOMText && trim($previous->data) === '') {
            $parent->removeChild($previous);
        }
        $parent->removeChild($node);
    }
}
