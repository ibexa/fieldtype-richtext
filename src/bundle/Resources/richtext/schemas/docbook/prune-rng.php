declare(strict_types=1);

/*
 * Generates pruned/docbook.rng and pruned/ezpublish.rng from docbook.rng and ezpublish.rng.
 *
 * libxml compiles the whole grammar on every validation, and most of the DocBook definitions
 * are never reachable from ezpublish.rng. pruned/docbook.rng keeps only the reachable
 * definitions, without annotations.
 *
 * libxml also applies every override in <include> by scanning the whole included grammar,
 * which costs more than compiling the pruned grammar itself. pruned/docbook.rng therefore
 * contains the start pattern and the definitions from ezpublish.rng's <include> in place of
 * the ones they replace, and pruned/ezpublish.rng is ezpublish.rng including it without
 * overrides.
 *
 * The files keep the original names: RichTextDocbookSchemaPass (5.0+) finds the base schema
 * in the validator resources by the "ezpublish.rng" file name.
 *
 * Usage: php prune-rng.php [target_dir]
 */

const RNG_NAMESPACE = 'http://relaxng.org/ns/structure/1.0';
const GENERATED_NOTICE = ' Pruned variant of DocBook generated by prune-rng.php from docbook.rng and ezpublish.rng, do not edit. ';

/**
 * @return DOMNode[]
 */
function queryNodes(
    DOMXPath $xpath,
    string $expression,
    ?DOMNode $contextNode = null
): array {
    $nodes = $xpath->query($expression, $contextNode);
    if ($nodes === false) {
        throw new RuntimeException("Invalid XPath expression '{$expression}'");
    }

    $result = [];
    foreach ($nodes as $node) {
        if ($node instanceof DOMNode) {
            $result[] = $node;
        }
    }

    return $result;
}

/**
 * @return DOMElement[]
 */
function queryElements(
    DOMXPath $xpath,
    string $expression,
    ?DOMNode $contextNode = null
): array {
    return array_values(array_filter(
        queryNodes($xpath, $expression, $contextNode),
        static fn (DOMNode $node): bool => $node instanceof DOMElement
    ));
}

function removeNode(DOMNode $node): void
{
    $parent = $node->parentNode;
    if ($parent === null) {
        return;
    }

    $previous = $node->previousSibling;
    if ($previous instanceof DOMText && trim($previous->data) === '') {
        $parent->removeChild($previous);
    }
    $parent->removeChild($node);
}

function loadSchema(string $path): DOMXPath
{
    $document = new DOMDocument();
    if (!$document->load($path)) {
        throw new RuntimeException("Cannot load '{$path}'");
    }

    $xpath = new DOMXPath($document);
    $xpath->registerNamespace('rng', RNG_NAMESPACE);

    return $xpath;
}

$targetDir = $argv[1] ?? __DIR__ . '/pruned';
if (!is_dir($targetDir) && !mkdir($targetDir, 0777, true)) {
    fwrite(STDERR, "Cannot create directory '{$targetDir}'\n");
    exit(1);
}

$docbookXPath = loadSchema(__DIR__ . '/docbook.rng');
$ezpublishXPath = loadSchema(__DIR__ . '/ezpublish.rng');
$docbook = $docbookXPath->document;
$ezpublish = $ezpublishXPath->document;

$docbookGrammar = $docbook->documentElement;
$includes = queryElements($ezpublishXPath, '/rng:grammar/rng:include');
if ($docbookGrammar === null || count($includes) !== 1) {
    fwrite(STDERR, "Expected a docbook.rng grammar and a single <include> in ezpublish.rng\n");
    exit(1);
}
$include = $includes[0];

// The DocBook license requires its copyright notice in all copies.
$licenseComments = queryNodes($docbookXPath, '/rng:grammar/comment()[following-sibling::rng:start]');

// Definitions inside <include> replace all included ones with the same name, combine or not.
$overridden = [];
foreach (queryElements($ezpublishXPath, './/rng:define', $include) as $define) {
    $overridden[$define->getAttribute('name')] = true;
}

$definitions = [];
foreach (queryElements($docbookXPath, '//rng:define') as $define) {
    $name = $define->getAttribute('name');
    if (!isset($overridden[$name])) {
        $definitions[$name][] = [$docbookXPath, $define];
    }
}
foreach (queryElements($ezpublishXPath, '//rng:define') as $define) {
    $definitions[$define->getAttribute('name')][] = [$ezpublishXPath, $define];
}

// libxml resolves the references of every definition, used or not.
$overridesStart = !empty(queryElements($ezpublishXPath, './/rng:start', $include));
$roots = queryElements($ezpublishXPath, '//rng:ref');
if (!$overridesStart) {
    $roots = array_merge($roots, queryElements($docbookXPath, '//rng:start//rng:ref'));
}

$reachable = [];
$queue = [];
foreach ($roots as $ref) {
    $queue[] = $ref->getAttribute('name');
}
while (!empty($queue)) {
    $name = array_pop($queue);
    if (isset($reachable[$name])) {
        continue;
    }
    $reachable[$name] = true;
    foreach ($definitions[$name] ?? [] as [$xpath, $define]) {
        foreach (queryElements($xpath, './/rng:ref', $define) as $ref) {
            $queue[] = $ref->getAttribute('name');
        }
    }
}

$undefined = array_keys(array_diff_key($reachable, $definitions));
if (!empty($undefined)) {
    fwrite(STDERR, 'References without a definition: ' . implode(', ', $undefined) . "\n");
    exit(1);
}

foreach (queryElements($docbookXPath, '//rng:define') as $define) {
    $name = $define->getAttribute('name');
    if (isset($overridden[$name]) || !isset($reachable[$name])) {
        removeNode($define);
    }
}
if ($overridesStart) {
    foreach (queryElements($docbookXPath, '//rng:start') as $start) {
        removeNode($start);
    }
}

// Appended after the included definitions, the order in which libxml combines them.
// The order matters: moving them before the DocBook definitions changes validation results.
while ($include->firstChild !== null) {
    $docbookGrammar->appendChild($docbook->importNode($include->firstChild, true));
    $include->removeChild($include->firstChild);
}

// Annotations are ignored by RELAX NG validation.
foreach (queryNodes($docbookXPath, '//comment() | //*[namespace-uri() != "' . RNG_NAMESPACE . '"]') as $node) {
    if (!in_array($node, $licenseComments, true)) {
        removeNode($node);
    }
}

while (!empty($emptyDivs = queryElements($docbookXPath, '//rng:div[not(*)]'))) {
    foreach ($emptyDivs as $div) {
        removeNode($div);
    }
}

foreach ([[$docbook, 'docbook.rng'], [$ezpublish, 'ezpublish.rng']] as [$document, $file]) {
    if ($document->documentElement !== null) {
        $document->insertBefore($document->createComment(GENERATED_NOTICE), $document->documentElement);
    }
    if ($document->save($targetDir . '/' . $file) === false) {
        fwrite(STDERR, "Cannot write '{$targetDir}/{$file}'\n");
        exit(1);
    }
}
